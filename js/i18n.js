let currentLang = 'ko';

function detectLanguage() {
    try {
        const saved = localStorage.getItem('portfolio-lang');
        if (saved === 'ko' || saved === 'en') return saved;
    } catch (e) { /* 저장소 차단 */ }
    return (navigator.language || 'ko').startsWith('ko') ? 'ko' : 'en';
}

function setLanguage(lang) {
    currentLang = lang;
    try { localStorage.setItem('portfolio-lang', lang); } catch (e) { /* 무시 */ }
    document.documentElement.lang = lang;
    const dict = translations[lang] || {};
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const text = dict[el.getAttribute('data-i18n')];
        if (text === undefined) return;
        el.textContent = text;
    });
    document.querySelectorAll('.lang-toggle').forEach(btn => {
        btn.textContent = lang === 'ko' ? 'EN' : 'KO';
    });
}

function initI18n() {
    setLanguage(detectLanguage());
    document.querySelectorAll('.lang-toggle').forEach(btn => {
        btn.addEventListener('click', () => setLanguage(currentLang === 'ko' ? 'en' : 'ko'));
    });
}
